    public static void Seed(AppDbContext db)
    {
        if (db.Subjects.Any()) return;

        db.Subjects.AddRange(Math(), Physics(), Chemistry(), Arabic());
        db.SaveChanges();
    }

    private static Unit MakeUnit(int order, string title, string description, params (string Title, string Content, int Minutes)[] lessons) => new()
    {
        Order = order,
        Title = title,
        Description = description,
        Lessons = lessons.Select((lesson, i) => new Lesson
        {
            Order = i + 1,
            Title = lesson.Title,
            Content = lesson.Content,
            DurationMinutes = lesson.Minutes
        }).ToList()
    };

    // correctIndex is the position of the right answer in the options list
    private static Question MakeQuestion(int order, string text, int correctIndex, params string[] options) => new()
    {
        Order = order,
        Text = text,
        Options = options.Select((option, i) => new Option { Text = option, IsCorrect = i == correctIndex }).ToList()
    };

